import streamlit as st
import pandas as pd
import plotly.express as px


# --------------------------------------------------
# 페이지 설정
# --------------------------------------------------

st.set_page_config(
    page_title="영화 데이터 그래프 도감 1 - 시간",
    page_icon="🎬",
    layout="wide"
)


# --------------------------------------------------
# 데이터 주소
# --------------------------------------------------

DATA_URL = (
    "https://raw.githubusercontent.com/greatsong/"
    "modudata/main/data/kobis_daily.csv"
)


# --------------------------------------------------
# 제목
# --------------------------------------------------

st.title("🎬 영화 데이터 그래프 도감 1 - 시간")

st.write(
    "365일간의 일별 박스오피스 데이터를 이용해 "
    "영화의 시간에 따른 변화를 살펴봅니다."
)


# --------------------------------------------------
# 데이터 불러오기
# utf-8-sig를 사용해서 파일 앞부분의 숨은 문자를 제거
# --------------------------------------------------

try:
    df = pd.read_csv(
        DATA_URL,
        encoding="utf-8-sig"
    )

except Exception as e:
    st.error("❌ 데이터를 불러오지 못했습니다.")
    st.write("오류 내용:", e)
    st.stop()


# --------------------------------------------------
# 열 이름에 혹시 남아 있을 수 있는 공백/숨은 문자 제거
# --------------------------------------------------

df.columns = (
    df.columns
    .astype(str)
    .str.strip()
)


# --------------------------------------------------
# 데이터 확인
# --------------------------------------------------

required_columns = [
    "날짜",
    "순위",
    "영화코드",
    "영화명",
    "일관객",
    "누적관객",
    "스크린수",
    "상영횟수"
]


missing_columns = [
    column
    for column in required_columns
    if column not in df.columns
]


if missing_columns:

    st.error("❌ 데이터의 열 이름을 제대로 읽지 못했습니다.")

    st.write(
        "현재 읽은 열:",
        list(df.columns)
    )

    st.write(
        "없는 열:",
        missing_columns
    )

    st.stop()


# --------------------------------------------------
# 날짜를 진짜 날짜 형식으로 변환
# 예: 20250901 → 2025-09-01
# --------------------------------------------------

df["날짜"] = pd.to_datetime(
    df["날짜"].astype(str),
    format="%Y%m%d",
    errors="coerce"
)


# --------------------------------------------------
# 숫자 데이터 숫자형으로 변환
# --------------------------------------------------

numeric_columns = [
    "순위",
    "영화코드",
    "일관객",
    "누적관객",
    "스크린수",
    "상영횟수"
]


for column in numeric_columns:

    df[column] = pd.to_numeric(
        df[column],
        errors="coerce"
    )


# --------------------------------------------------
# 영화명 문자열 정리
# --------------------------------------------------

df["영화명"] = (
    df["영화명"]
    .astype(str)
    .str.strip()
)


# --------------------------------------------------
# 날짜순으로 정렬
# --------------------------------------------------

df = df.sort_values(
    "날짜"
).reset_index(drop=True)


# ==================================================
# 그래프 1
# ==================================================

st.divider()

st.header("📈 그래프 1. 영화별 일관객 변화")

st.write(
    "영화를 하나 선택하면 해당 영화의 날짜별 일관객 변화를 볼 수 있습니다."
)


# --------------------------------------------------
# 영화 목록 만들기
# --------------------------------------------------

movie_list = sorted(
    df["영화명"]
    .dropna()
    .unique()
)


# 영화가 제대로 읽혔는지 확인
if len(movie_list) == 0:

    st.error("❌ 영화 목록을 불러오지 못했습니다.")

    st.write(
        "현재 데이터 행 수:",
        len(df)
    )

    st.stop()


# --------------------------------------------------
# 영화 선택 드롭다운
# --------------------------------------------------

selected_movie = st.selectbox(
    "🎬 영화를 선택하세요.",
    movie_list
)


# --------------------------------------------------
# 선택한 영화 데이터만 추출
# --------------------------------------------------

movie_df = df[
    df["영화명"] == selected_movie
].copy()


# 날짜순 정렬
movie_df = movie_df.sort_values(
    "날짜"
)


# --------------------------------------------------
# 선택한 영화 데이터 확인
# --------------------------------------------------

if movie_df.empty:

    st.warning(
        "선택한 영화의 데이터가 없습니다."
    )

    st.stop()


# ==================================================
# Plotly 선그래프
# ==================================================

fig = px.line(
    movie_df,
    x="날짜",
    y="일관객",
    markers=True,
    title=f"「{selected_movie}」 날짜별 일관객 변화",
    labels={
        "날짜": "날짜",
        "일관객": "일관객 수"
    }
)


# --------------------------------------------------
# 마우스를 올렸을 때 표시되는 내용
# --------------------------------------------------

fig.update_traces(
    hovertemplate=(
        "날짜: %{x|%Y-%m-%d}"
        "<br>일관객: %{y:,}명"
        "<extra></extra>"
    )
)


# --------------------------------------------------
# 그래프 설정
# --------------------------------------------------

fig.update_layout(
    height=550,
    hovermode="x unified",
    xaxis_title="날짜",
    yaxis_title="일관객 수"
)


# --------------------------------------------------
# 그래프 출력
# --------------------------------------------------

st.plotly_chart(
    fig,
    use_container_width=True
)


# --------------------------------------------------
# 이 그래프로 알 수 있는 것
# --------------------------------------------------

st.subheader("💡 이 그래프로 알 수 있는 것")

st.text_area(
    "그래프를 보고 알 수 있는 점을 적어 보세요.",
    placeholder=(
        "예: 이 영화는 개봉 직후 일관객 수가 가장 높았고 "
        "시간이 지나면서 점차 감소하는 모습을 보인다."
    ),
    height=100,
    key="graph1_note"
)


# ==================================================
# 그래프 2
# ==================================================

st.divider()

st.header("📊 그래프 2")

st.info(
    "여기에 두 번째 그래프를 추가할 예정입니다."
)

st.subheader("💡 이 그래프로 알 수 있는 것")

st.text_area(
    "두 번째 그래프에서 알 수 있는 점을 적어 보세요.",
    placeholder="이 그래프를 통해 알 수 있는 내용을 적어 보세요.",
    height=100,
    key="graph2_note"
)


# ==================================================
# 그래프 3
# ==================================================

st.divider()

st.header("📊 그래프 3")

st.info(
    "여기에 세 번째 그래프를 추가할 예정입니다."
)

st.subheader("💡 이 그래프로 알 수 있는 것")

st.text_area(
    "세 번째 그래프에서 알 수 있는 점을 적어 보세요.",
    placeholder="이 그래프를 통해 알 수 있는 내용을 적어 보세요.",
    height=100,
    key="graph3_note"
)


# ==================================================
# 데이터 정보
# ==================================================

st.divider()

st.subheader("📋 데이터 정보")

st.write(
    f"전체 데이터: **{len(df):,}개 행**"
)

st.write(
    f"영화 종류: **{len(movie_list):,}개**"
)

st.write(
    f"데이터 기간: "
    f"**{df['날짜'].min().strftime('%Y-%m-%d')} ~ "
    f"{df['날짜'].max().strftime('%Y-%m-%d')}**"
)
